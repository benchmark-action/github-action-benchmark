import { buildComment } from '../src/write';
import { Benchmark, BenchmarkResult } from '../src/extract';
import { FakedOctokit, fakedRepos } from './fakedOctokit';
import dedent from 'dedent';

interface RepositoryPayloadSubset {
    private: boolean;
    html_url: string;
}

const gitHubContext = {
    repo: {
        repo: 'repo',
        owner: 'user',
    },
    payload: {
        repository: {
            private: false,
            html_url: 'https://github.com/user/repo',
        } as RepositoryPayloadSubset | null,
    },
    workflow: 'Workflow name',
};

jest.mock('@actions/github', () => ({
    get context() {
        return gitHubContext;
    },
    getOctokit(token: string) {
        return new FakedOctokit(token);
    },
}));

afterEach(function () {
    fakedRepos.clear();
});

describe('buildComment', () => {
    it('should build comment when previous benchmarks are 0 and biggerIsBetter returns false', () => {
        const comment = buildComment(
            'TestSuite',
            {
                date: 12345,
                commit: {
                    id: 'testCommitIdCurrent',
                    author: {
                        name: 'TestUser',
                    },
                    committer: {
                        name: 'TestUser',
                    },
                    message: 'Test current commit message',
                    url: 'https://test.previous.commit.url',
                },
                tool: 'cargo',
                benches: [
                    {
                        value: 0,
                        name: 'TestBench<1>',
                        unit: 'testUnit',
                    },
                    {
                        value: 1,
                        name: 'TestBench<2>',
                        unit: 'testUnit',
                    },
                    {
                        value: -1,
                        name: 'TestBench<3>',
                        unit: 'testUnit',
                    },
                ],
            },
            {
                date: 12345,
                commit: {
                    id: 'testCommitIdPrevious',
                    author: {
                        name: 'TestUser',
                    },
                    committer: {
                        name: 'TestUser',
                    },
                    message: 'Test previous commit message',
                    url: 'https://test.previous.commit.url',
                },
                tool: 'cargo',
                benches: [
                    {
                        value: 0,
                        name: 'TestBench<1>',
                        unit: 'testUnit',
                    },
                    {
                        value: 0,
                        name: 'TestBench<2>',
                        unit: 'testUnit',
                    },
                    {
                        value: 0,
                        name: 'TestBench<3>',
                        unit: 'testUnit',
                    },
                ],
            },
        );

        expect(comment).toEqual(dedent`
            # TestSuite
            
            <details>
            
            | Benchmark suite | Current: testCommitIdCurrent | Previous: testCommitIdPrevious | Ratio |
            |-|-|-|-|
            | \`TestBench<1>\` | \`0 testUnit\` | \`0 testUnit\` | \`1\` |
            | \`TestBench<2>\` | \`1 testUnit\` | \`0 testUnit\` | \`+∞\` |
            | \`TestBench<3>\` | \`-1 testUnit\` | \`0 testUnit\` | \`-∞\` |
            
            </details>
            
            This comment was automatically generated by [workflow](https://github.com/user/repo/actions?query=workflow%3AWorkflow%20name) using [github-action-benchmark](https://github.com/marketplace/actions/continuous-benchmark).
        `);
    });

    it('should build comment when current benchmarks are 0 and biggerIsBetter returns true', () => {
        const comment = buildComment(
            'TestSuite',
            {
                date: 12345,
                commit: {
                    id: 'testCommitIdCurrent',
                    author: {
                        name: 'TestUser',
                    },
                    committer: {
                        name: 'TestUser',
                    },
                    message: 'Test current commit message',
                    url: 'https://test.previous.commit.url',
                },
                tool: 'benchmarkjs',
                benches: [
                    {
                        value: 0,
                        name: 'TestBench<1>',
                        unit: 'testUnit',
                    },
                    {
                        value: 0,
                        name: 'TestBench<2>',
                        unit: 'testUnit',
                    },
                    {
                        value: 0,
                        name: 'TestBench<3>',
                        unit: 'testUnit',
                    },
                ],
            },
            {
                date: 12345,
                commit: {
                    id: 'testCommitIdPrevious',
                    author: {
                        name: 'TestUser',
                    },
                    committer: {
                        name: 'TestUser',
                    },
                    message: 'Test previous commit message',
                    url: 'https://test.previous.commit.url',
                },
                tool: 'benchmarkjs',
                benches: [
                    {
                        value: 0,
                        name: 'TestBench<1>',
                        unit: 'testUnit',
                    },
                    {
                        value: 1,
                        name: 'TestBench<2>',
                        unit: 'testUnit',
                    },
                    {
                        value: -1,
                        name: 'TestBench<3>',
                        unit: 'testUnit',
                    },
                ],
            },
        );

        expect(comment).toEqual(dedent`
            # TestSuite
            
            <details>
            
            | Benchmark suite | Current: testCommitIdCurrent | Previous: testCommitIdPrevious | Ratio |
            |-|-|-|-|
            | \`TestBench<1>\` | \`0 testUnit\` | \`0 testUnit\` | \`1\` |
            | \`TestBench<2>\` | \`0 testUnit\` | \`1 testUnit\` | \`+∞\` |
            | \`TestBench<3>\` | \`0 testUnit\` | \`-1 testUnit\` | \`-∞\` |
            
            </details>
            
            This comment was automatically generated by [workflow](https://github.com/user/repo/actions?query=workflow%3AWorkflow%20name) using [github-action-benchmark](https://github.com/marketplace/actions/continuous-benchmark).
        `);
    });

    describe('value formatting', () => {
        function suite(bench: BenchmarkResult): Benchmark {
            return {
                date: 12345,
                commit: {
                    id: 'testCommitId',
                    author: { name: 'TestUser' },
                    committer: { name: 'TestUser' },
                    message: 'Test commit message',
                    url: 'https://test.commit.url',
                },
                tool: 'customSmallerIsBetter',
                benches: [bench],
            };
        }

        function renderValue(bench: BenchmarkResult): string {
            const comment = buildComment('TestSuite', suite(bench), suite(bench), false);
            const line = comment.split('\n').find((l) => l.startsWith('| `bench`'));
            if (line === undefined) {
                throw new Error(`Benchmark row not found in comment:\n${comment}`);
            }
            return line.split('|')[2].trim();
        }

        const cases: Array<[string, BenchmarkResult, string]> = [
            ['bare nanoseconds', { name: 'bench', value: 25000, unit: 'ns' }, '`25μs`'],
            ['bare microseconds', { name: 'bench', value: 25000, unit: 'us' }, '`25ms`'],
            ['bare milliseconds', { name: 'bench', value: 25000, unit: 'ms' }, '`25s`'],
            ['bare seconds', { name: 'bench', value: 100, unit: 's' }, '`1m 40s`'],
            ['nanoseconds per iteration', { name: 'bench', value: 25000, unit: 'ns/iter' }, '`25μs/iter`'],
            ['microseconds per iteration', { name: 'bench', value: 25000, unit: 'us/iter' }, '`25ms/iter`'],
            ['nanoseconds per op', { name: 'bench', value: 25000, unit: 'ns/op' }, '`25μs/op`'],
            [
                'range in nanoseconds',
                { name: 'bench', value: 25000, unit: 'ns/iter', range: '± 1000' },
                '`25μs/iter`<br>(`± 1μs`)',
            ],
            [
                'range in microseconds',
                { name: 'bench', value: 25000, unit: 'us/iter', range: '± 1.5' },
                '`25ms/iter`<br>(`± 1.5μs`)',
            ],
            [
                'unrecognized range is unchanged',
                { name: 'bench', value: 25000, unit: 'ns/iter', range: '± 2%' },
                '`25μs/iter`<br>(`± 2%`)',
            ],
            ['unknown unit is unchanged', { name: 'bench', value: 5, unit: 'testUnit' }, '`5 testUnit`'],
            [
                'unsupported time unit is unchanged',
                { name: 'bench', value: 20, unit: 'ops/sec', range: '+-20' },
                '`20 ops/sec`<br>(`+-20`)',
            ],
        ];

        for (const [description, bench, expected] of cases) {
            it(`formats ${description}`, () => {
                expect(renderValue(bench)).toBe(expected);
            });
        }
    });
});
